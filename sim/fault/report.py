"""Summarise results.json as report.md.

python3 report.py
"""
import collections
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
S_LABEL = {'U54': 'S1', 'U56': 'S2', 'Q4': 'S3', 'Q3': 'S4', 'Q5': 'S5', 'Q1': 'S8', 'U1': 'S9', 'U58': 'S11',
           'R3': 'shunt', 'R10': 'current-sense', 'R8': 'divider bottom', 'R4': 'SIG+ 10k', 'R5': 'SIG- 10k',
           'U2': 'signal buffers', 'U7': 'bus amplifiers', 'U8': 'monitor buffers', 'U9': 'converter',
           'U3': 'S6/S7/S10, LC_G drive', 'U4': 'TX_G, S8, S9, S11 drive', 'U6': 'current source',
           'U5': 'reference', 'U10': '+/-2.5 V LDO', 'U11': 'channel eFuse', 'U12': '-5 V pump', 'U13': '1.8 V LDO',
           'D1': 'S8 gate Zener', 'D8': 'S4 gate Zener', 'D52': 'S4 gate Zener', 'F1': '24 V fuse'}


def fmt(x, unit):
    if x is None:
        return '-'
    a = abs(x)
    if unit == 'A':
        return '%.3g A' % x if a >= 1 else '%.3g mA' % (x * 1e3)
    if unit == 'W':
        return '%.3g W' % x if a >= 1 else '%.3g mW' % (x * 1e3)
    return '%.3g %s' % (x, unit)


def label(ref):
    return '%s (%s)' % (ref, S_LABEL[ref]) if ref in S_LABEL else ref


def limit_txt(v):
    if v['lo'] is not None and v['hi'] is not None:
        if v['lo'] == -v['hi']:
            return '±' + fmt(v['hi'], v['unit'])
        return '%s to %s' % (fmt(v['lo'], v['unit']), fmt(v['hi'], v['unit']))
    return ('≤ ' + fmt(v['hi'], v['unit'])) if v['hi'] is not None else ('≥ ' + fmt(v['lo'], v['unit']))


def group(r):
    c = r['case']
    f = c['fault']
    if f is None:
        return 'baseline'
    if f[0] == 'short':
        return 'short'
    sign = '+' if c['vmax'] > 0 else '-'
    return '%s28V %s' % (sign, f[2])


def case_txt(c):
    f = c['fault']
    s = '%s, %s%s, %s' % (c['power'], c['config'], ', S11 closed' if c['shield'] else '', c['sensor'])
    if f and f[0] == 'V':
        s += ', %s %+g V %s' % (f[1], c['vmax'], f[2])
    elif f:
        s += ', %s shorted to %s' % (f[1], f[2])
    return s


def main():
    res = json.load(open(os.path.join(HERE, 'results.json')))
    failed = [r for r in res if r['status'] != 'ok']
    out = ['# GP channel 1: DC fault sweep', '',
           '%d cases; %d did not finish (listed at the end). Generated by report.py from results.json.' % (
               len(res), len(failed)), '']

    order = ['+28V 30mA', '+28V 5A', '-28V 30mA', '-28V 5A', 'short', 'baseline']
    title = {'+28V 30mA': '+28 V, limited to 30 mA (REQ-15 against a current-limited source)',
             '+28V 5A': '+28 V, limited to 5 A (a low-impedance source; OI-5)',
             '-28V 30mA': '-28 V, limited to 30 mA (beyond REQ-15)',
             '-28V 5A': '-28 V, limited to 5 A (beyond REQ-15)',
             'short': 'Contacts shorted in pairs, channel running',
             'baseline': 'No fault'}
    for kind in ('damage', 'trip', 'function'):
        out += ['## %s' % {'damage': 'Absolute maximum ratings exceeded',
                           'trip': 'Protection acting', 'function': 'Rails out of regulation or back-powered'}[kind], '']
        for g in order:
            agg = collections.OrderedDict()
            for r in res:
                if group(r) != g:
                    continue
                for v in r['violations']:
                    if v['kind'] != kind:
                        continue
                    k = (v['ref'], v['what'])
                    a = agg.setdefault(k, dict(n=0, worst=None, first=None, contacts=set(), powers=set(), configs=set(),
                                                 sensors=set(), v=v))
                    a['n'] += 1
                    c = r['case']
                    if c['fault']:
                        a['contacts'].add(c['fault'][1] if c['fault'][0] == 'V' else '%s-%s' % tuple(c['fault'][1:]))
                    a['powers'].add(c['power'])
                    a['configs'].add(c['config'] + ('+S11' if c['shield'] else ''))
                    a['sensors'].add(c['sensor'])
                    excess = abs(v['value']) - (abs(v['hi']) if v['hi'] is not None else abs(v['lo']))
                    if a['worst'] is None or excess > a['worst'][0]:
                        a['worst'] = (excess, v['value'], case_txt(c))
                    if v['first'] is not None and (a['first'] is None or abs(v['first']) < abs(a['first'])):
                        a['first'] = v['first']
            if not agg:
                continue
            out += ['### %s' % title[g], '',
                    '| Part | Limit | Worst | From | Contacts | Power | Configurations | Sensors | Cases | Worst case |',
                    '|---|---|---|---|---|---|---|---|---|---|']
            for (ref, what), a in sorted(agg.items(), key=lambda kv: (kv[0][0] == 'rail', kv[0])):
                v = a['v']
                out.append('| %s: %s | %s | %s | %s | %s | %s | %s | %s | %d | %s |' % (
                    label(ref), what, limit_txt(v), fmt(a['worst'][1], v['unit']),
                    ('%+g V' % a['first']) if a['first'] is not None and g not in ('short', 'baseline') else '-',
                    ', '.join(sorted(a['contacts'])) or '-', ', '.join(sorted(a['powers'])),
                    ', '.join(sorted(a['configs'])), ', '.join(sorted(a['sensors'])), a['n'], a['worst'][2]))
            out.append('')
    if failed:
        out += ['## Cases that did not finish', '', '| Case | Reached |', '|---|---|']
        for r in failed:
            out.append('| %s | %s |' % (case_txt(r['case']), fmt(r['reached'], 'V')))
        out.append('')
    open(os.path.join(HERE, 'report.md'), 'w').write('\n'.join(out))
    print('report.md: %d lines' % len(out))


if __name__ == '__main__':
    main()
